-- Р14 — owner apply only. Do not run through Prisma migrate/db push.
-- Індекси під асинхронну фазу глобального пошуку (docs/DECISIONS.md#р14):
-- «всі шо якось шукаються мають мати гарні індекси в бд».
--
-- Але знайшлося дещо більше за пошук. Виміряно на робочій базі 2026-08-21:
--
--   ІНДЕКСИ НА pers:  pers_pkey, pers_sharetoken_key  — і все.
--   pg_stat_user_tables: seq_scan=3227, seq_tup_read=27962845, idx_scan=39578
--
-- Тобто pers.user_id — це зовнішній ключ БЕЗ індексу, і 3 227 послідовних сканувань
-- уже прочитали 27,9 млн рядків. Це не майбутня проблема пошуку, це поточна вартість
-- звичайних листингів персонажа. Пошук лише додасться зверху.
--
-- Асиметрія, схожа на пропущений рядок у моделі: PersFolder, PersAdditionalUser і
-- PersFolderMember мають @@index([userId]), а Pers — найбільша з них — не має жодного
-- @@index узагалі.
--
-- Після ручного застосування: bun run db:pull (підтягне @@index у prisma/schema.prisma,
-- який руками не правиться) → коміт.
--
-- CONCURRENTLY не потрібне: pers — 11 МБ, звичайний CREATE INDEX відпрацює за частки
-- секунди. Якщо все ж захочеться уникнути локу — CONCURRENTLY не можна виконувати
-- всередині транзакційного блоку, тобто файл треба ганяти без BEGIN/COMMIT.


-- 1. КРИТИЧНО. Обслуговує і пошук, і всі наявні листинги
--    (src/server/db/pers-actions.ts:115,146). Зрізає скан з 8 929 рядків до ≤557.
--    Виміряно: EXPLAIN на реальному запиті пошуку дає Seq Scan, Buffers: shared hit=1190
--    — 9,3 МБ через буфери на кожне натискання клавіші, щоб віддати 10 рядків.
CREATE INDEX pers_user_id_idx ON public.pers USING btree (user_id);

-- 2. ВАРТО. Пошук у межах папки, і головне — DELETE папки більше не робить
--    seq scan по pers для перевірки посилань. 81 різне значення на 8 929 рядків.
CREATE INDEX pers_folder_id_idx ON public.pers USING btree (folder_id);

-- 3. НИЗЬКИЙ ПРІОРИТЕТ, але поки руки в базі. Self-FK без індексу: обхід ланцюга
--    снапшотів (6 418 рядків) іде послідовним скануванням.
CREATE INDEX pers_parentpersid_idx ON public.pers USING btree (parentpersid);


