-- KR33.4 — «Демонічна спадщина» тифлінга 2024 → «Почварна спадщина».
--
-- Fiend у словнику — «Почвара» (тип істоти, «Почварне відновлення»); рішення власника
-- 2026-09-13 — «Почвара всюди». Риса й фічі варіантів переіменовуються сідом за engName, а
-- група вибору в race_choice_option шукається сідом за українською назвою: без цього оновлення
-- сід створив би поруч другу групу з новими option_id, а старі три рядки лишилися б.
-- Оновлення на місці зберігає option_id, на які посилаються вибори персонажів.
--
-- Порядок:
--   1) власник застосовує файл до робочої бази;
--   2) агент синкає spells_test через ./scripts/apply-db-change.sh;
--   3) сід 2024 переписує назви фіч.

UPDATE race_choice_option
SET choice_group_name = 'Почварна спадщина'
WHERE ruleset = 'RULES_2024'
  AND choice_group_name = 'Демонічна спадщина';
