-- Одна колонка: звідки клас потрапив у перелік заклинання.
--
-- Навіщо. Рішення власника 2026-08-23 (питання 3 KR16.2): розширені списки заклинань
-- (`classVariant` у 5etools, здебільшого TCE) беремо дефолтно — але з показом книги, яка їх
-- дає. Без місця під цю книгу 46 заклинань 2014 лишаються незакритими: додати клас можна,
-- а сказати «за Tasha's Cauldron of Everything» — ні. Саме ці 46 і є вся різниця, що
-- лишилася у звірці 2014 після виправної фази (`classes` 46, решта полів 0).
--
-- Семантика:
--   NULL  — клас із базового переліку своєї книги. Так стоїть у всіх наявних рядках.
--   не NULL — клас доданий розширеним списком із названої книги; UI показує це поруч.
--
-- Колонка NULLABLE і без DEFAULT: жоден наявний рядок не змінюється, застосування безпечне
-- на живій базі й не потребує вікна простою. Тип — той самий enum `Source`, що й у `spell`,
-- щоб «TCOE» не роз'їхалося з «TCE» рядком.

ALTER TABLE public.spell_classes
  ADD COLUMN IF NOT EXISTS source public."Source";

COMMENT ON COLUMN public.spell_classes.source IS
  'Книга розширеного списку заклинань, що дала класу це заклинання. NULL — базовий перелік.';

