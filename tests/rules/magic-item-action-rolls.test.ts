import { describe, expect, it } from "vitest";
import { findItemActionChargeCost, findItemRolls } from "@/rules/magic-item-action-rolls";

describe("ціна дії предмета в зарядах", () => {
  it.each([
    ["**Промінь (витрачає 1 заряд).** Атака +7 до влучання.", 1],
    ["Ви можете витратити 2 заряди персня, щоб застосувати закляття.", 2],
    ["Ви можете дією витратити 1 її заряд і обрати ціллю гуманоїда.", 1],
    ["Ви можете витратити 3 заряди, щоб застосувати з нього закляття.", 3],
  ])("%s → %i", (text, cost) => {
    expect(findItemActionChargeCost(text)).toBe(cost);
  });

  it.each([
    "Ви можете дією витратити 1 або більше зарядів, щоб застосувати закляття.",
    "Ви можете витратити до 3 його зарядів, щоб завдати додаткової шкоди.",
    "Предмет має 7 зарядів.",
  ])("кількість вирішує гравець або ціни немає: %s", (text) => {
    expect(findItemActionChargeCost(text)).toBeNull();
  });
});

describe("кубики в описі предмета", () => {
  it("відновлення зарядів не кидок, а кубики хітів — лікування", () => {
    const text = "Посох має 10 зарядів і відновлює 1к6 + 4 витрачених зарядів на світанку. Істота відновлює 2к8 + 2 хітів. Влучання: 4к10 некротичної шкоди.";
    expect(findItemRolls(text).map((spot) => spot.roll)).toEqual([
      { kind: "heal", count: 2, sides: 8, bonus: 2 },
      { kind: "damage", count: 4, sides: 10, bonus: 0, damageType: "NECROTIC" },
    ]);
  });

  it.each([
    "Протрубіть у ріг, і зʼявляться 2к4 + 2 воїни-берсерки.",
    "Намисто має 1к4 + 4 намистини.",
    "Перстень вміщує закляття загальним рівнем до 1к6 − 1.",
    "Коли ви витрачаєте останній заряд, киньте 1к20.",
  ])("кубики без шкоди чи хітів — не кнопка: %s", (text) => {
    expect(findItemRolls(text)).toEqual([]);
  });
});
