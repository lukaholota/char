import { describe, expect, it } from "vitest";
import creatures2014 from "@/lib/generated/creatures.json";
import creatures2024 from "@/lib/generated/creatures2024.json";
import dictionary from "@/lib/refs/dictionary.json";

const OLD_TERM = /Чаклування/g;
const RATIFIED_TERM = /Чаротворення/g;

function count(pattern: RegExp, value: unknown): number {
  return JSON.stringify(value).match(pattern)?.length ?? 0;
}

describe("KR12.8 — Spellcasting має одну назву в обох редакціях", () => {
  it("прибиває owner-approved термін у словнику", () => {
    expect(dictionary.DND_DICTIONARY.statblockFeatures.Spellcasting).toBe("Чаротворення");
  });

  it("замінює всі 148 уживань у каталозі 2014", () => {
    // 687 → 704: партія 1 KR16.3 привела 17 нових істот і заступила три спадкові записи.
    // Жодна з них не має блоку заклинань, тому 125 уживань не зрушили.
    // 704 → 722: партія 2 привела 18 нових і заступила два спадкові записи. Тут уживання
    // зрушили — 125 → 127: блок заклинань несуть `Sage` і `Skull Lasher of Myrkul`.
    // 722 → 738: партія 3 привела 16 нових і заступила чотири спадкові записи. Уживання
    // зрушили 127 → 134 — блок заклинань несуть сім записів: Xvart Warlock of Raxivort,
    // Berbalang, Bozak Draconian, Crystal Dragon Wyrmling, Draconian Mage, Dragon Speaker,
    // Emerald Dragon Wyrmling. Восьмий каст партії — `Darkling Elder` — це дія «Темрява»,
    // а не блок Spellcasting, тому в число не входить.
    // 738 → 756: партія 4 привела 18 нових і заступила два спадкові записи. Уживання зрушили
    // 134 → 138 — блок заклинань несуть чотири записи: Topaz Dragon Wyrmling, Choldrith,
    // Deathlock Wight і Uthgardt Shaman (останній доїхав після ратифікації «Ботійської»).
    // 756 → 773: партія 5 привела 17 нових і заступила три спадкові записи. Блок заклинань
    // несуть шість записів партії: Sapphire і Amethyst Dragon Wyrmling, Dybbuk,
    // Firbolg Primeval Warden, Hobgoblin Devastator і Master of Souls. Уживання зрушили
    // 138 → 143, а не 144: заступлений `Hobgoblin Devastator` уже ніс «Чаротворення» у
    // спадковому записі, тож він дає нуль приросту, а не одиницю.
    // 773 → 787: партія 6 привела 14 нових і заступила шість спадкових. Блок заклинань несуть
    // вісім записів партії, але три заступлені (обидва юань-ті й `Adult Oblex`) уже несли
    // «Чаротворення», тож приріст 5, а не 8.
    // 787 → 804: партія 7 привела 17 нових і заступила один спадковий запис. Блок заклинань
    // несуть вісім записів партії, і приріст рівно 8: заступлений `Young Crystal Dragon`
    // блоку заклинань у спадковому записі **не мав** (перевірено по зрізу до партії), тож він
    // дає +1, а не нуль, — на відміну від `Hobgoblin Devastator` партії 5.
    // 804 → 821: партія 8 привела 17 нових і заступила три спадкові записи. Блок заклинань
    // несуть пʼять записів партії, і приріст рівно 5: жоден із трьох заступлених у спадковому
    // записі «Чаротворення» не мав (перевірено по зрізу до партії).
    // 821 → 823: два розблоковані записи партії 7 (`Tlincalli`, `Mouth of Grolantor`) доїхали
    // після ратифікації термінів. Блоку заклинань не має жоден, тож 161 не зрушило.
    // 823 → 835: партія 9 привела 12 нових і заступила шість спадкових записів. Уживань
    // «Чаротворення» 161 → 168: блок заклинань несуть шість записів партії — два нові
    // (`Young Moonstone Dragon`, `Hydroloth`) і чотири заступлені, з яких три в спадковому
    // записі його не мали (перевірено по зрізу до партії).
    // 835 → 851: партія 10 привела 16 нових і заступила чотири спадкові записи. Уживань
    // «Чаротворення» 168 → 175: блок заклинань несуть шість записів партії, і всі чотири
    // заступлені вже мали «Чаротворення» у спадковому записі, тож приріст дають два нові
    // (`Cloud Giant Smiling One`, `Spring Eladrin`) плюс переписані блоки заступлених.
    // 851 → 866: партія 11 привела 15 нових і заступила пʼять спадкових записів. Уживань
    // «Чаротворення» 176 → 190: блок заклинань несуть 12 записів партії, а обидва самоцвітні
    // дракони й `Oinoloth` називають його двічі — у блоці й у легендарній дії чи мультиатаці.
    // 866 → 883: партія 12 привела 17 нових і заступила два спадкові записи. Уживань
    // «Чаротворення» 190 → 199: блок заклинань несуть сім записів партії, а обидва дракони
    // з лігвом (`Adult Emerald Dragon`, `Adult Moonstone Dragon`) називають його двічі — у
    // блоці й у легендарній дії. Заступлений `Githyanki Supreme Commander` приросту не дає:
    // він уже ніс «Чаротворення» у спадковому записі (перевірено по зрізу до партії).
    // 883 → 900: партія 13 привела 17 нових і заступила три спадкові записи. Уживань
    // «Чаротворення» 199 → 213: блок заклинань несуть 12 записів партії, а обидва самоцвітні
    // дракони, `Ґітзерай анарх` і `Драконячий уламок` називають його двічі — у блоці й у
    // легендарній дії.
    // 900 → 918: партія 14 привела 17 нових і заступила три спадкові записи, плюс
    // розблокований `Wersten Kern`. Уживань «Чаротворення» 213 → 229; приріст 16 знято
    // позаписно: по одному дають `Wersten Kern`, `Amnizu`, `Cloud Giant Destiny Gambler` і
    // `Storm Giant Tempest Caller`, по два — `Bael`, `Lord Soth`, `Iggwilv the Witch Queen`
    // і всі три стародавні самоцвітні дракони (блок заклинань плюс легендарна дія). Жоден
    // із трьох заступлених записів «Чаротворення» у спадковій формі не мав.
    // 918 → 935: партія 15 привела 17 нових і заступила три спадкові записи. Уживань
    // «Чаротворення» 229 → 246: блок заклинань несуть 14 записів партії, а стародавні
    // сапфіровий і аметистовий дракони, `Moloch`, `Molydeus` і `Miirym` називають його двічі —
    // у блоці й у легендарній дії. Заступлений `Elder Brain Dragon` приросту не дає взагалі:
    // у книзі FTOD блоку заклинань у нього немає, а спадковий запис ніс «Уроджене чаклування».
    // 935 → 955: партія 16 привела 20 нових записів і не заступила жодного. Уживань
    // «Чаротворення» 246 → 259; приріст 13 знято позаписно: блок заклинань несуть
    // `Zuggtmoy`, `Graz'zt`, `Yeenoghu`, `Baalzebul` і `Levistus`, а решта приросту — з дії
    // лігва «Накладання заклинання», спільної для шести архідияволів (`Belial`, `Fierna`,
    // `Glasya`, `Baalzebul`, `Levistus`, `Mammon`). `Graz'zt` називає термін тричі — у назві
    // дії, у Мультиатаці й у легендарній дії. `Bel` приросту не дає: у нього «Вроджене
    // чаклування», а не «Чаротворення».
    // 955 → 959: партія 17 — хвіст черги 2014, чотири записи, жодного заступленого.
    // Уживань «Чаротворення» 259 → 264; приріст 5 знято позаписно: `Mephistopheles` і
    // `Asmodeus` називають термін двічі (блок заклинань плюс спільна дія лігва архідияволів
    // «Накладання заклинання»), `Dispater` — один раз, бо блоку заклинань у нього немає, а
    // дія лігва є. `Scion of Stronmaus` приросту не дає: заклинань він не накладає взагалі.
    // 959 → 974: партія 20 — 15 прадраконів книги FTD. Уживань «Чаротворення» 264 → 274;
    // приріст 10 знято позаписно: його дають лише пʼять самоцвітних прадраконів, по два на
    // запис — назва дії «Чаротворення (Псіоніка)» і легендарна дія «Псіоніка», текст якої
    // відсилає до неї. Хроматичні й металеві приросту не дають: заклинань вони не накладають.
    expect(creatures2014).toHaveLength(974);
    expect(count(OLD_TERM, creatures2014)).toBe(0);
    expect(count(RATIFIED_TERM, creatures2014)).toBe(274);
  });

  it("не змінює каталог 2024", () => {
    // 514 → 530: партія 18 KR16.3 — перша партія редакції 2024 в цьому KR, шістнадцять
    // записів, жодного заступленого.
    // 530 → 531: партія 19 (`Reanimated Companion`, один запис) лежала в
    // `data/5etools/creature-batches.json`, але каталог під неї не перебудовували —
    // розбіжність вилізла на ребілді KR17.5 (партія 3, 2026-08-29). Блока заклинань
    // запис не несе, тому число «Чаротворення» нижче не зрушило.
    expect(creatures2024).toHaveLength(531);
    expect(count(OLD_TERM, creatures2024)).toBe(0);
    // 209 → 220: приріст 11 знято позаписно. Блок заклинань несуть шість записів партії 18
    // (`Drow of Lolth`, `Drow Elite Warrior of Lolth` — через «Магію Підземного світу»,
    // `Cultist of Bhaal`, `Drow Mage of Lolth`, `Drow Priestess of Lolth`, `Cultist of Bane`,
    // `Cultist of Myrkul`, `Animal Lord`), а дроу-маг, дроу-жриця й культист Бейна називають
    // термін двічі — у блоці й у бонусній дії чи мультиатаці.
    expect(count(RATIFIED_TERM, creatures2024)).toBe(220);
  });
});
