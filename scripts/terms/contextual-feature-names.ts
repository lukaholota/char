/// Назви, які не піддаються термінізації: та сама англійська назва означає різну частину тіла
/// у різних істот, і одна українська форма на всіх зробила б текст неправильним. Рішення
/// власника 2026-09-09: ратифікована форма діє в **обох** редакціях, а такі випадки «просто
/// йдуть цілими назвами — для крабів, слонів, котів».
///
/// `Gore` слона й мамонта — удар **бивнями**, не рогами: ратифіковане «Буцання» дало б слонові
/// удар рогами. `Claw` краба й скорпіона — **клішня**, а не кіготь.
///
/// Перелік тримається за slug істоти, бо це властивість істоти, а не редакції: обидві редакції
/// читають той самий рядок. Реєстр — один на проєкт: його читає і прохід ратифікації, і гейт
/// `5etools-creatures.test.ts`, інакше вони розійшлися б у протилежні боки, як розійшлися
/// бестіарії до цієї правки — 2014 казав «Удар бивнями», 2024 «Буцання», а краби навпаки.
const CONTEXTUAL_FEATURE_NAMES: Record<string, Record<string, string>> = {
  Gore: {
    elephant: "Удар бивнями",
    mammoth: "Удар бивнями",
  },
  Claw: {
    crab: "Клішня",
    "giant-crab": "Клішня",
    "giant-scorpion": "Клішня",
  },
};

export function findContextualFeatureName(english: string, slug: string): string | undefined {
  return CONTEXTUAL_FEATURE_NAMES[english]?.[slug];
}

export function listContextualSlugs(english: string): string[] {
  return Object.keys(CONTEXTUAL_FEATURE_NAMES[english] ?? {});
}
