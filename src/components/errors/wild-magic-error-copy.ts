export const WILD_MAGIC_ERROR_COPIES: readonly WildMagicErrorCopy[] = WILD_MAGIC_SURGE_TABLE_ROWS.map((row) => {
  const featuredCopy = FEATURED_ERROR_COPIES.find((copy) => copy.surgeRoll === row.roll);
  if (featuredCopy) return featuredCopy;

  const { title, joke } = SURGE_TITLE_AND_JOKE[row.roll];
  return {
    surgeRoll: row.roll,
    title,
    description: `${formatSurgeEffect(row.description)} ${joke}`,
  };
});

function formatSurgeEffect(description: string): string {
  return description
    .replace(/<a [^>]+>([^<]+)<\/a>/g, "$1")
    .replace(/\s+\[[^\]]+\]/g, "");
}

/// Серверний рендер не має випадковості, спільної з клієнтом, тому бере варіант з `digest`
/// помилки: однаковий HTML на сервері й під час гідрації, і без JavaScript текст теж є.
export function findSeededCopyIndex(seed: string | undefined): number {
  if (!seed) return 0;
  let hash = 0;
  for (const char of seed) hash = (hash * 31 + char.codePointAt(0)!) >>> 0;
  return hash % WILD_MAGIC_ERROR_COPIES.length;
}

export function drawRandomCopyIndex(random: () => number = Math.random): number {
  return Math.floor(random() * WILD_MAGIC_ERROR_COPIES.length);
}
