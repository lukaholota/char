/// Форми, зняті ратифікацією 2026-08-23 і рішеннями власника 2026-08-30 (питання 20, 21).
/// Визначення одне на обидві редакції: 2014-гейт тримав їх у себе, а 2024-гейт заводив би
/// копію — саме той клас дефекту, з якого в цьому репозиторії виростають розбіжні двійники.
/// Межі слова й переліки закінчень навмисні: «чарівник», «чародій», «чаротворча»,
/// «Причарований», «неушкодженими», «ушкоджує» законні й червонити не мають.

/// spell. «чари» словника немає ніде — ні як термін, ні як синонім ([Р18], питання 20).
export const SPELL_WORD = /(?<![\p{L}])чар(?:и|ів|ам|ами|ах)(?![\p{L}])/iu;

/// cast a spell — зрощення, яке гейт ловив окремо ще до зводу всього слова.
export const CAST_SPELL_PHRASE = /створю\S*\s+(?:ці\s+)?чар/iu;

/// damage. Іменникові форми; «пошкодження» має власний рядок у 2014-гейті.
export const DAMAGE_NOUN = /(?<![\p{L}])ушкоджен(?:ь|н)/iu;

/// Armor Class. Рішення власника 2026-08-30: «КБ» — єдиний коректний варіант.
export const ARMOR_CLASS_RETIRED = /(?<![\p{L}])КЗ(?![\p{L}])/u;

/// challenge rating. Канон — «показник небезпеки»; «клас» і «рівень» — дві зняті форми.
export const CHALLENGE_RATING_RETIRED = /(?:клас|рівн)[а-яіїєʼ'’]*\s+небезпеки/iu;

/// stat block. Канон — «статблок». Іменник-перший («блок характеристик/параметрів/…») і
/// прикметник-перший («статистичний блок») — дві форми того самого терміна, знайдені в різних
/// каталогах (KR17.5 партія 3 — перша, KR32.1 — друга, `Giant Insect` у каталозі 2024).
export const STAT_BLOCK_RETIRED =
  /(?<![\p{L}])блок\S*\s+(?:параметр|характеристик|показник|статистик|стану)|статистичн\S*\s+блок/iu;

/// KR32.1: один детектор на всі зняті форми, ратифіковані 2026-08-23/30, замість копії на
/// кожен гейт чи носій. Обидва гейти заклинань і звід носіїв поза каталогом заклинань
/// ([O32](../../docs/o32-corpus-terms/README.md)) читають саме цей перелік.
export const CORPUS_RETIRED_FORMS: { label: string; pattern: RegExp }[] = [
  { label: "заклинання", pattern: SPELL_WORD },
  { label: "накладаєте заклинання", pattern: CAST_SPELL_PHRASE },
  { label: "шкода", pattern: DAMAGE_NOUN },
  { label: "КБ", pattern: ARMOR_CLASS_RETIRED },
  { label: "показник небезпеки", pattern: CHALLENGE_RATING_RETIRED },
  { label: "статблок", pattern: STAT_BLOCK_RETIRED },
];
