/// Поверхні, де «що нового» доречне: головна обох редакцій і сторінки персонажів. На каталог,
/// відкритий із пошуку Google, модалка не виходить — людина прийшла читати заклинання,
/// а не наші новини. Конструктор теж поза списком: перебивати створення персонажа гірше,
/// ніж не показати зовсім.
export function isWhatsNewSurface(pathname: string): boolean {
  if (pathname === "/" || pathname === "/2024") return true;
  if (pathname.startsWith("/char/create")) return false;
  return pathname.startsWith("/char") || pathname.startsWith("/pers");
}
