def pair_label_marker(text):
    match = re.match(r"^([^{}|:«»()\[\]*.,;!?\n]+?)\{\{([^{}|]+)\}\}", text)
    if not match:
        return text
    ukrainian, original = match.group(1).strip(), match.group(2)
    if len(ukrainian.split()) == len(original.split()):
        return text
    return "{{%s|%s}}" % (ukrainian, original) + text[match.end():]


FRAGMENTS = {key: pair_label_marker(value) for key, value in refs.expand_all(FRAGMENTS).items()}
