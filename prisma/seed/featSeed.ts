/// Текстові поля рис читає ще й адресний сідер `scripts/seed-2014-feat-text.ts`: повний
/// `seedFeats` перестворює звʼязки `grantsFeature`, а звід терміна цього не потребує.
export function readFeatSeedInputs(): FeatCreateInput[] {
  return feats;
}
export async function seedFeats(prisma: PrismaClient) {
  console.log("🎭 Seeding Feats...");

  for (const featData of feats) {
    const { grantsFeature, ...rest } = featData;

    await prisma.feat.upsert({
      where: { name_ruleset: { name: rest.name, ruleset: ACTIVE_RULESET } },
      update: {
        ...(rest as any),
        grantsFeature: grantsFeature
          ? {
              deleteMany: {},
              connect: grantsFeature.connect,
            }
          : undefined,
      },
      create: {
        ...(rest as any),
        grantsFeature: grantsFeature
          ? {
              create: grantsFeature.create,
            }
          : undefined,
      },
    });
    await new Promise((resolve) => setTimeout(resolve, 100));
  }

  console.log(`✅ Seeded ${feats.length} feats`);
}
